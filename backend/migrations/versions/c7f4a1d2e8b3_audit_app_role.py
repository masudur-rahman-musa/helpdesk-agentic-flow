# An earlier change decision C: a fixed constant, never configuration. A configurable
# role name would be an identifier interpolated into SQL, which is an injection
# surface this migration has no reason to own. Pinned by
# `test_audit_db_role.py::ROLE_NAME` and the whole module that reads it.
ROLE_NAME = "helpdesk_app"

# the design says the application role has INSERT and SELECT only on the audit
# log. An earlier change decision C deferred that to this row because the compose app
# user OWNED the database, and an owner's grants mean nothing: the append-only
# trigger was the entire enforcement. A table owner can also disable a trigger,
# so the trigger alone never stopped a compromised service from rewriting the
# log. This migration gives the services a role that is not the owner.
#
# Which refusal arrives is the point, not merely that one does. As this role an
# UPDATE, DELETE or TRUNCATE on `audit_events` is refused by the privilege
# check with SQLSTATE 42501, before the trigger's P0001 is ever reached. That
# distinction is pinned by
# `test_audit_db_role.py::test_restricted_role_update_on_audit_events_is_refused_by_privilege`
# and its DELETE and TRUNCATE twins.
_APPEND_ONLY = ("SELECT", "INSERT")
_READ_WRITE = ("SELECT", "INSERT", "UPDATE")
_READ_WRITE_DELETE = ("SELECT", "INSERT", "UPDATE", "DELETE")

# An earlier change decision D: explicit per-table grants, never ALTER DEFAULT
# PRIVILEGES. Default privileges would hand a future audit-like table UPDATE
# and DELETE on the day it is created, which is the exact failure this row
# exists to prevent. The cost is that a new table needs a line here, and
# `test_audit_db_role.py::test_expected_grant_map_covers_exactly_the_metadata_tables`
# is what says so.
#
# Only three rows differ from read-write:
# - `audit_events` is append-only.
# - `idempotency_keys` has expired keys purged (`core/repository.py`).
# - `policy_chunks` has a document's chunks deleted on reingest
#   (`rag/chunks.py`); nothing else in the codebase deletes a row.
TABLE_GRANTS: dict[str, tuple[str, ...]] = {
    "tenants": _READ_WRITE,
    "departments": _READ_WRITE,
    "users": _READ_WRITE,
    "systems": _READ_WRITE,
    "roles": _READ_WRITE,
    "role_templates": _READ_WRITE,
    "sod_rules": _READ_WRITE,
    "grants": _READ_WRITE,
    "tickets": _READ_WRITE,
    "audit_events": _APPEND_ONLY,
    "idempotency_keys": _READ_WRITE_DELETE,
    "access_requests": _READ_WRITE,
    "access_reviews": _READ_WRITE,
    "review_items": _READ_WRITE,
    "policy_documents": _READ_WRITE,
    "policy_chunks": _READ_WRITE_DELETE,
    "sessions": _READ_WRITE,
    "messages": _READ_WRITE,
    "notifications": _READ_WRITE,
}

# `seq` is BIGINT GENERATED BY DEFAULT AS IDENTITY, and Postgres names its
# sequence after the table and the column. A table grant does not carry the
# sequence, so an INSERT would fail on the sequence rather than the table.
# Pinned by `test_audit_db_role.py::test_restricted_role_holds_usage_on_the_audit_events_sequence`.
AUDIT_SEQUENCE_NAME = "audit_events_seq_seq"

# Roles are cluster-global while this migration runs against one database, so
# "did we create it?" has to survive in the cluster rather than in the schema.
# The comment on the role is that record: an environment that provisioned
# `helpdesk_app` itself (a managed Postgres, a Terraform run) carries no
# comment, so the downgrade leaves that role alone.
_CREATED_MARKER = f"created by alembic revision {revision}"

# The role is created with NOLOGIN on purpose: a password in a migration is a
# secret in code. `docker/postgres/init-app-role.sh` grants LOGIN
# with a password from the environment. Where that script never ran because an
# existing `pgdata` volume skipped it, the role still exists and a service
# started against it fails on connect, loudly, instead of silently falling back
# to the owner DSN.
_CREATE_ROLE = f"""
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = '{ROLE_NAME}') THEN
        CREATE ROLE "{ROLE_NAME}" NOLOGIN;
        COMMENT ON ROLE "{ROLE_NAME}" IS '{_CREATED_MARKER}';
    END IF;
END
$$
"""

# `GRANT ... ON DATABASE` takes a name, not an expression, and the database this
# runs against is whichever DSN Alembic was pointed at (a temp database, in the
# suite). `format` with `%I` quotes the name `current_database()` reports, so a
# name needing quoting cannot break the statement.
_GRANT_CONNECT = f"""
DO $$
BEGIN
    EXECUTE format('GRANT CONNECT ON DATABASE %I TO "{ROLE_NAME}"', current_database());
END
$$
"""

_REVOKE_CONNECT = f"""
DO $$
BEGIN
    EXECUTE format('REVOKE CONNECT ON DATABASE %I FROM "{ROLE_NAME}"', current_database());
END
$$
"""

# Dropping a role fails while any grant in ANY database still depends on it,
# which is exactly the case when a second database in the same cluster is still
# migrated to head. That is not an error to fail the downgrade over: the role is
# still in use, so leaving it is the correct outcome. The handler names that one
# SQLSTATE and nothing else, so a permissions problem still raises.
_DROP_ROLE_IF_CREATED = f"""
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_roles
        WHERE rolname = '{ROLE_NAME}'
          AND shobj_description(oid, 'pg_authid') = '{_CREATED_MARKER}'
    ) THEN
        BEGIN
            DROP ROLE "{ROLE_NAME}";
        EXCEPTION WHEN dependent_objects_still_exist THEN
            RAISE NOTICE 'role {ROLE_NAME} is still granted in another database, keeping it';
        END;
    END IF;
END
$$
"""


def upgrade() -> None:
    """Upgrade schema."""
    op.execute(_CREATE_ROLE)
    # CONNECT and schema USAGE are granted to PUBLIC by default, but a hardened
    # environment revokes both, and this role then cannot reach a single table
    # it has been granted. Stating them makes the migration the whole answer.
    op.execute(_GRANT_CONNECT)
    op.execute(f'GRANT USAGE ON SCHEMA public TO "{ROLE_NAME}"')
    for table_name, privileges in TABLE_GRANTS.items():
        op.execute(f'GRANT {", ".join(privileges)} ON TABLE {table_name} TO "{ROLE_NAME}"')
    op.execute(f'GRANT USAGE ON SEQUENCE {AUDIT_SEQUENCE_NAME} TO "{ROLE_NAME}"')


def downgrade() -> None:
    """Downgrade schema."""
    for table_name in TABLE_GRANTS:
        op.execute(f'REVOKE ALL ON TABLE {table_name} FROM "{ROLE_NAME}"')
    op.execute(f'REVOKE ALL ON SEQUENCE {AUDIT_SEQUENCE_NAME} FROM "{ROLE_NAME}"')
    op.execute(f'REVOKE USAGE ON SCHEMA public FROM "{ROLE_NAME}"')
    op.execute(_REVOKE_CONNECT)
    op.execute(_DROP_ROLE_IF_CREATED)
